"""
Bundled HuggingFace file index (metadata/hf-index.json).

Lists every model file in the Comfy-Org and Kijai HuggingFace repos with
size and SHA-256 - the files ComfyUI's official templates and most shared
workflows use. Looked up before the HuggingFace API: instant, works for
files in subfolders (split_files/...) that API search can't see, and can
identify a file by hash. Regenerated by tools/build_hf_index.py.
"""

import json
import logging
import os
import threading
from typing import Any, Dict, List, Optional

from .huggingface import get_huggingface_download_url

logger = logging.getLogger(__name__)

INDEX_PATH = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
                          'metadata', 'hf-index.json')

_lock = threading.Lock()
_index: Optional[Dict[str, Any]] = None


def _load() -> Dict[str, Any]:
    """Load the index once and build filename/hash lookups."""
    global _index
    with _lock:
        if _index is not None:
            return _index

        files: List[Dict[str, Any]] = []
        authors: List[str] = []
        try:
            with open(INDEX_PATH, 'r', encoding='utf-8') as f:
                data = json.load(f)
            files = [entry for entry in data.get('files', []) if isinstance(entry, dict)]
            authors = data.get('authors', [])
        except FileNotFoundError:
            logger.debug("Model Linker: no bundled HF index")
        except Exception as e:
            logger.warning(f"Model Linker: could not read HF index: {e}")

        # Earlier authors win when several repos carry the same filename:
        # Comfy-Org's copies are the ones official templates point at
        def priority(entry):
            author = entry.get('repo_id', '').split('/', 1)[0]
            return authors.index(author) if author in authors else len(authors)

        by_filename: Dict[str, List[Dict[str, Any]]] = {}
        by_sha256: Dict[str, Dict[str, Any]] = {}
        for entry in sorted(files, key=priority):
            filename = entry.get('filename', '')
            by_filename.setdefault(filename, []).append(entry)
            by_filename.setdefault(filename.lower(), []).append(entry)
            sha = (entry.get('sha256') or '').lower()
            if sha:
                by_sha256.setdefault(sha, entry)

        _index = {'by_filename': by_filename, 'by_sha256': by_sha256}
        return _index


def _to_result(entry: Dict[str, Any], match_type: str) -> Dict[str, Any]:
    return {
        'source': 'huggingface',
        'url_source': 'hf_index',
        'repo_id': entry['repo_id'],
        'filename': entry['filename'],
        'path': entry['path'],
        'url': get_huggingface_download_url(entry['repo_id'], entry['path']),
        'size': entry.get('size'),
        'sha256': entry.get('sha256'),
        'match_type': match_type,
    }


def lookup_by_filename(filename: str) -> Optional[Dict[str, Any]]:
    """Exact filename match (case-insensitive fallback), folder ignored."""
    if not filename:
        return None
    name = filename.replace('\\', '/').rsplit('/', 1)[-1]
    by_filename = _load()['by_filename']
    entries = by_filename.get(name) or by_filename.get(name.lower())
    return _to_result(entries[0], 'exact') if entries else None


def lookup_by_sha256(sha256: str) -> Optional[Dict[str, Any]]:
    if not sha256:
        return None
    entry = _load()['by_sha256'].get(sha256.lower())
    return _to_result(entry, 'hash') if entry else None
